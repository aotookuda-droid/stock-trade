#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
軸馬選定チェックリスト（減点方式）スコアラー
================================================================

「何を見ればいいのか？ 軸馬選定チェックリスト」を実行可能にしたツール。
各馬に該当する“危険信号”を入れると、軸(アンカー)としての減点スコアを算出する。

思想：加点方式はNG。減点方式で「軸に据えてよいか」を判定する（prediction_method ③）。
- スコアが 0 に近いほど軸向き。
- 深いマイナスは「軸不可」だが、穴/相手(3着候補)としては当然アリ。
  → これは“軸の資格”を測るフィルターであって、馬券から消す道具ではない。

使い方:
  $ python3 simulations/axis_checklist.py        # サンプル比較を表示
  コード内 evaluate({...}) に「馬名: [該当項目]」を渡すと、ランキングして出力。

依存ライブラリなし。
"""

from __future__ import annotations


# 減点項目（点数, グループ）。文言はチェックリスト原文に準拠。
CHECKLIST: dict[str, int] = {
    # -5点（軸として最も危険）
    "前走『逃げて』好走":        -5,
    "初ダート/初の芝":          -5,
    "距離延長ローテ":            -5,
    "ダートで前走牝馬限定戦":    -5,
    # -4点
    "昇級初戦":                  -4,
    "前走が特殊条件":            -4,
    "前走ローカル競馬場":        -4,
    # -3点
    "6ヶ月以上の休み明け":       -3,
    "芝の外枠/ダートの内枠":     -3,
    "トップハンデの斤量":        -3,
    # -2点
    "急坂コースで好走なし":      -2,
    "馬体重が±15kg以上変動":     -2,
    # -1点
    "右回り/左回りで好走なし":   -1,
    "冬の牝馬/夏の牡馬":         -1,
}


def score(flags: list[str]) -> int:
    """該当項目リスト → 合計減点。未知の項目は例外で気付けるようにする。"""
    total = 0
    for f in flags:
        if f not in CHECKLIST:
            raise KeyError(f"チェックリストに無い項目: {f!r}\n  有効な項目: {list(CHECKLIST)}")
        total += CHECKLIST[f]
    return total


def verdict(s: int) -> str:
    """減点合計から軸適性の目安（しきい値は相対評価用。好みで調整可）。"""
    if s == 0:
        return "◎ 軸に最適（減点なし）"
    if s >= -3:
        return "◯ 軸候補（軽微な不安）"
    if s >= -6:
        return "△ 軸はやや不安（相手・紐向き）"
    return "✕ 軸不可（消し or 大穴の一発狙いのみ）"


def evaluate(horses: dict[str, list[str]]) -> None:
    """馬名 → 該当項目 の辞書を受け取り、減点の浅い順（＝軸向き順）に出力。"""
    rows = [(name, score(flags), flags) for name, flags in horses.items()]
    rows.sort(key=lambda r: r[1], reverse=True)  # 0に近い順
    print("=" * 70)
    print(" 軸馬選定チェックリスト（減点方式）— 0に近いほど軸向き")
    print("=" * 70)
    for name, s, flags in rows:
        print(f"\n  {name}  合計 {s:>3}点  → {verdict(s)}")
        for f in flags:
            print(f"      {CHECKLIST[f]:>3}  {f}")
    print("\n" + "-" * 70)
    print(" ※使い方：候補を全頭スコアリングし、最も0に近い馬を軸に。")
    print("   深いマイナスは『軸にするな』であって『買うな』ではない（穴/相手では可）。")
    print("   減点ゼロでも“買い”の根拠（コース適性・上がり・展開）は別途必要。")


# ---- サンプル（使い方の例。実レースでは該当項目を差し替える）----------------
SAMPLE = {
    "A（堅実型）":   [],                                        # 減点なし＝理想の軸
    "B（中位人気）": ["前走ローカル競馬場", "トップハンデの斤量"],
    "C（人気だが危険）": ["前走『逃げて』好走", "6ヶ月以上の休み明け", "馬体重が±15kg以上変動"],
}


if __name__ == "__main__":
    evaluate(SAMPLE)
